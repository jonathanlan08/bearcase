import { chromium } from "@playwright/test";
const OUT = "/Users/jonathanlan/bearcase/docs/screenshots";
const b = await chromium.launch({ args: ["--enable-webgl", "--ignore-gpu-blocklist", "--use-angle=swiftshader"] });
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
const p = await ctx.newPage();
await p.goto("http://localhost:3000/", { waitUntil: "networkidle" }); await p.waitForTimeout(2500);
await p.screenshot({ path: `${OUT}/01-landing-hero.png` });
const total = await p.evaluate(() => { const el = document.querySelector("main > div"); return el.offsetHeight - window.innerHeight; });
await p.evaluate((y) => window.scrollTo(0, y), Math.round(0.55 * total)); await p.waitForTimeout(1500);
await p.screenshot({ path: `${OUT}/01b-landing-hero-contradictions.png` });
await p.evaluate(() => window.scrollTo(0, document.body.scrollHeight * 0.42)); await p.waitForTimeout(1200);
await p.screenshot({ path: `${OUT}/01c-landing-sections.png` });
await p.goto("http://localhost:3000/demo"); await p.waitForURL(/\/app\/deals\//, { timeout: 90000 });
const base = p.url().replace(/\/?$/, "");
await p.goto(`${base}/claims`); await p.waitForTimeout(900);
await p.screenshot({ path: `${OUT}/04-claim-audit.png` });
await p.getByRole("button", { name: /Open chat/ }).click();
await p.getByRole("button", { name: "Why was adjusted EBITDA reduced?", exact: true }).last().click();
await p.waitForTimeout(3500);
await p.screenshot({ path: `${OUT}/12-ask-the-deal.png` });
await p.goto(`${base}`); await p.waitForTimeout(900);
await p.screenshot({ path: `${OUT}/02-overview.png` });
await b.close(); console.log("ok");
